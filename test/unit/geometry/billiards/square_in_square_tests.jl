# Unit tests for the square-within-square billiard constructor and structure:
#   src/geometry/billiards/square_in_square.jl   (SquareWithinSquareBilliard{T}, SquareWithinSquareBilliard(a; positions, sizes))
# Reference object: a MultiplyConnectedDomain with id 1 and genus n whose holes are SymmetricHoles, one per obstacle square of side
# `sizes[i]` centred at (d_i, d_i) with the positions sorted ascending. All obstacles sit on the diagonal y = x, so the registry
# always contains DiagonalReflection. Hole i (counted from the lower left) has domain id i + 1, its piece is a Polygon, and the
# pieces of its images carry ids i + 1 + 100 k with id_stride 100.
# Three configurations:
#   * general (shifted or non-mirrored obstacles): registry {DiagonalReflection}, outer Polygon (-a,-a), (a,-a), (a,a) with
#     SymmetryWall(1,2) on the diagonal, each hole piece the half below the diagonal, 2 pieces per hole;
#   * mirrored about the origin (positions and sizes invariant under d -> -d, the default): registry of 3 elements (DiagonalReflection,
#     XYAxisReflection, AntiDiagonalReflection), outer wedge (0,0), (a,-a), (a,a); an obstacle at d > 0 stands for itself and its
#     mirror image, 4 pieces, an obstacle at the origin is the quarter of its square in the wedge; fundamental area is area / 4;
#   * a single obstacle centered at the origin: registry D4_symmetry() (7 elements), outer triangle (a,0), (a,a), (0,0) with
#     SymmetryWall(1,2) and SymmetryWall(7,8), hole piece the triangle (0,0), (h,0), (h,h) with h = size / 2, 8 pieces;
#     fundamental area is area / 8.
# get_boundary_curves rejects any billiard with holes and a non-empty registry.
# Closed forms: area 4 a^2 - sum(sizes^2), corner angles, full physical loop lengths (8 a for the outer square, 4 size per obstacle).
# Guards: a > 0, equal lengths of positions and sizes, positive sizes, holes strictly inside, no overlap. No eigen solves.

# Total arc length of a loop of LineSegments.
sws_loop_length(loop) = sum(c -> c.length, loop)

using StaticArrays: SVector

@testset "SquareWithinSquareBilliard fields" begin
    sws = SquareWithinSquareBilliard(1.0)
    @test sws isa SquareWithinSquareBilliard{Float64}
    @test sws isa AbsBilliard
    @test sws.fundamental_domain isa MultiplyConnectedDomain{Float64}
    @test sws.symmetries isa SymmetryRegistry
    @test fieldnames(SquareWithinSquareBilliard) == (:fundamental_domain, :symmetries)
    @test @inferred(SquareWithinSquareBilliard(1.0)) isa SquareWithinSquareBilliard{Float64}
end

@testset "SquareWithinSquareBilliard symmetries" begin
    # default obstacles are mirror symmetric about the origin: the group generated by both diagonal reflections
    sws = SquareWithinSquareBilliard(1.0)
    @test length(sws.symmetries) == 3
    @test typeof.(get_symmetries(sws)) == (DiagonalReflection, AntiDiagonalReflection)
    # a single obstacle away from the origin only keeps the reflection about the diagonal
    shifted = SquareWithinSquareBilliard(1.0; positions=[0.1], sizes=[0.4])
    @test length(shifted.symmetries) == 1
    @test typeof.(get_symmetries(shifted)) == (DiagonalReflection,)
    @test length(SquareWithinSquareBilliard(1.0; positions=[0.5, -0.5], sizes=[0.1, 0.2]).symmetries) == 1
    # a single obstacle at the origin has the full D4 symmetry: 7 non-identity elements, G' = D4 of order 8
    sym = SquareWithinSquareBilliard(1.0; positions=[0.0], sizes=[0.4])
    @test length(sym.symmetries) == 7
    @test length(get_symmetry_group(sym)) == 7
    @test [g.sym_id for g in sym.symmetries] == [g.sym_id for g in D4_symmetry()]
    @test typeof.(get_symmetries(sym)) == (DiagonalReflection, YAxisReflection)
end

@testset "SquareWithinSquareBilliard curves" begin
    dom = SquareWithinSquareBilliard(1.0).fundamental_domain
    @test dom.id == 1
    # mirrored default: one outer wedge and one stored hole (the obstacle at +1/2, its mirror image at -1/2 is a piece)
    @test length(dom.subdomains) == 1
    @test length(dom.holes) == 1
    hole = only(dom.holes)
    @test hole isa SymmetricHole{Float64}
    outer = dom.subdomains[1]
    @test outer isa Polygon{Float64}
    @test outer.id == 1
    @test outer.corners == [SVector(0.0, 0.0), SVector(1.0, -1.0), SVector(1.0, 1.0)]
    @test all(c -> c isa LineSegment{Float64}, outer.boundary)
    @test all(c -> c.domain_id == 1, outer.boundary)
    @test [c.segment_id for c in outer.boundary] == [1, 2, 3]
    @test [typeof(c.bc) for c in outer.boundary] == [SymmetryWall, SpecularReflection, SymmetryWall]
    # hole piece: the half below the diagonal of the square of side 1/4 centred at (1/2, 1/2), domain id 3
    @test hole.piece isa Polygon{Float64}
    @test hole.piece.id == 3
    @test hole.piece.corners == [SVector(0.375, 0.375), SVector(0.625, 0.375), SVector(0.625, 0.625)]
    @test [typeof(c.bc) for c in hole.piece.boundary] == [SpecularReflection, SpecularReflection, SymmetryWall]
    @test length(hole.symmetries) == 3
    @test length(hole.pieces) == 4
    @test hole.id_stride == 100
    @test hole.center == SVector(0.0, 0.0)
end

@testset "SquareWithinSquareBilliard curves (centered obstacle)" begin
    dom = SquareWithinSquareBilliard(1.0; positions=[0.0], sizes=[0.4]).fundamental_domain
    @test dom.id == 1
    @test length(dom.subdomains) == 1
    @test length(dom.holes) == 1
    @test dom.holes[1] isa SymmetricHole{Float64}
    # outer region: the fundamental triangle 0 <= y <= x <= a, one physical side and the two symmetry walls (diagonal, x axis)
    outer_dom = dom.subdomains[1]
    @test outer_dom isa Polygon{Float64}
    @test outer_dom.id == 1
    side, diagonal, axis = outer_dom.boundary
    @test all(c -> c isa LineSegment{Float64}, outer_dom.boundary)
    @test side.bc isa SpecularReflection
    @test diagonal.bc isa SymmetryWall
    @test axis.bc isa SymmetryWall
    @test all(c -> c.domain_id == 1, outer_dom.boundary)
    @test [side.pt0, side.pt1] == [SVector(1.0, 0.0), SVector(1.0, 1.0)]
    @test [diagonal.pt0, diagonal.pt1] == [SVector(1.0, 1.0), SVector(0.0, 0.0)]
    @test [axis.pt0, axis.pt1] == [SVector(0.0, 0.0), SVector(1.0, 0.0)]
    # hole: the triangle (0,0), (h,0), (h,h) with h = size / 2, pieces of its D4 images, domain id 2 and id_stride 100
    hole = dom.holes[1]
    @test hole.piece isa Polygon{Float64}
    @test hole.piece.id == 2
    @test length(hole.symmetries) == 7
    @test length(hole.pieces) == 8
    @test hole.id_stride == 100
    @test hole.center == SVector(0.0, 0.0)
    side_piece = only(c for c in hole.piece.boundary if c.bc isa SpecularReflection)
    @test [side_piece.pt0, side_piece.pt1] == [SVector(0.2, 0.0), SVector(0.2, 0.2)]
    @test count(c -> c.bc isa SymmetryWall, hole.piece.boundary) == 2
end

@testset "SquareWithinSquareBilliard hole count" begin
    # a shifted single obstacle: outer region is the lower triangle, the hole piece the half below the diagonal
    one_hole = SquareWithinSquareBilliard(1.0; positions=[0.1], sizes=[0.4]).fundamental_domain
    @test length(one_hole.holes) == 1
    @test one_hole.holes[1] isa SymmetricHole{Float64}
    @test one_hole.holes[1].piece.id == 2
    @test length(one_hole.holes[1].pieces) == 2
    @test one_hole.subdomains[1].corners == [SVector(-1.0, -1.0), SVector(1.0, -1.0), SVector(1.0, 1.0)]
    @test one_hole.holes[1].piece.corners[1] ≈ SVector(-0.1, -0.1) atol = 1e-14

    # mirrored positions: the obstacle at -d is a piece of the one at +d, the centered one is its own hole (ids follow sorted positions)
    three_holes = SquareWithinSquareBilliard(1.0; positions=[0.5, -0.5, 0.0], sizes=[0.2, 0.2, 0.2]).fundamental_domain
    @test length(three_holes.holes) == 2
    @test [h.piece.id for h in three_holes.holes] == [3, 4]
    @test three_holes.holes[1].piece.corners[1] == SVector(0.0, 0.0)
    @test three_holes.holes[2].piece.corners[1] ≈ SVector(0.4, 0.4) atol = 1e-14

    # unsorted positions are sorted with their sizes (not mirrored here): the hole at 0.5 has side 0.1 and the one at -0.5 side 0.2
    unsorted = SquareWithinSquareBilliard(1.0; positions=[0.5, -0.5], sizes=[0.1, 0.2]).fundamental_domain
    @test length(unsorted.holes) == 2
    @test unsorted.holes[1].piece.corners[1] ≈ SVector(-0.6, -0.6) atol = 1e-14
    @test unsorted.holes[2].piece.corners[1] ≈ SVector(0.45, 0.45) atol = 1e-14
end

@testset "SquareWithinSquareBilliard topology" begin
    sws = SquareWithinSquareBilliard(1.0)
    # genus equals the number of obstacles, also when mirror images are pieces of a single stored hole
    @test genus(sws) == 2
    @test genus(sws.fundamental_domain) == 2
    @test genus(SquareWithinSquareBilliard(1.0; positions=[0.0], sizes=[0.4])) == 1
    @test genus(SquareWithinSquareBilliard(1.0; positions=[0.1], sizes=[0.4])) == 1
    @test genus(SquareWithinSquareBilliard(1.0; positions=[0.5, -0.5, 0.0], sizes=[0.2, 0.2, 0.2])) == 3
    # default: the outer wedge contributes its physical side, each of the two obstacles one loop of 2 pieces x 2 curves
    comps = boundary_components(sws)
    @test length(comps) == genus(sws) + 1
    @test [length(c) for c in comps] == [1, 4, 4]
    @test [[c.domain_id for c in comp] for comp in comps] == [[1], [3, 3, 103, 103], [203, 203, 303, 303]]
    @test boundary_component_is_hole(sws) == [false, true, true]
    # geometric components keep the fundamental-domain geometry: the outer boundary plus one loop per hole piece
    @test length(geometric_boundary_components(sws)) == 1 + length(only(sws.fundamental_domain.holes).pieces)
    @test hole_domain_ids(sws) == [3, 103, 203, 303]
    @test [is_hole_curve(sws, c) for c in get_all_curves(sws)] == [fill(false, 3); fill(true, 12)]

    # shifted obstacle: two outer physical sides, one hole loop made of the 2 curves of each of the 2 pieces
    shifted = SquareWithinSquareBilliard(1.0; positions=[0.1], sizes=[0.4])
    comps = boundary_components(shifted)
    @test [length(c) for c in comps] == [2, 4]
    @test [[c.domain_id for c in comp] for comp in comps] == [[1, 1], [2, 2, 102, 102]]
    @test boundary_component_is_hole(shifted) == [false, true]
    @test hole_domain_ids(shifted) == [2, 102]
    @test component_of_domain_id(shifted) == Dict(1 => 0, 2 => 1, 102 => 1)

    # centered obstacle: the physical side of the fundamental triangle and the 8 pieces of the obstacle
    sym = SquareWithinSquareBilliard(1.0; positions=[0.0], sizes=[0.4])
    comps = boundary_components(sym)
    @test [length(c) for c in comps] == [1, 8]
    @test [c.domain_id for c in comps[2]] == [2 + 100k for k in 0:7]
    @test boundary_component_is_hole(sym) == [false, true]
    @test hole_domain_ids(sym) == [2 + 100k for k in 0:7]
    @test component_of_domain_id(sym) == Dict(1 => 0, [2 + 100k => 1 for k in 0:7]...)
    @test [is_hole_curve(sym, c) for c in get_all_curves(sym)] == [fill(false, 3); fill(true, 24)]
end

@testset "SquareWithinSquareBilliard geometry" begin
    sws = SquareWithinSquareBilliard(1.0)
    # area 4 a^2 - sum of the squared side lengths
    @test area(sws) ≈ 4 - 2 * 0.25^2 rtol = 1e-12
    @test area(SquareWithinSquareBilliard(1.0; positions=[0.0], sizes=[0.4])) ≈ 4 - 0.16 rtol = 1e-12
    @test area(SquareWithinSquareBilliard(2.0)) ≈ 16 - 2 * 0.5^2 rtol = 1e-12
    # fundamental area: area / |registry + identity|
    @test fundamental_area(sws) ≈ area(sws) / 4 rtol = 1e-12
    # centered obstacle: the full physical area is unchanged, the fundamental area is the area / 8 of the reduced domain
    sym = SquareWithinSquareBilliard(1.0; positions=[0.0], sizes=[0.4])
    @test fundamental_area(sym) ≈ (4 - 0.16) / 8 rtol = 1e-12
    @test fundamental_area(SquareWithinSquareBilliard(1.0; positions=[0.1], sizes=[0.4])) ≈ (4 - 0.16) / 2 rtol = 1e-12
    @test is_inside(sym, SVector(0.7, 0.3)) === true
    @test is_inside(sym, SVector(0.1, 0.05)) === false       # inside the obstacle piece (0,0), (0.2,0), (0.2,0.2)
    @test is_inside(sym, SVector(-0.5, 0.9)) === false       # other quadrants lie outside the fundamental triangle
    @test is_inside(sym, SVector(1.2, 0.1)) === false
    # membership in the fundamental wedge (0,0), (1,-1), (1,1) minus the obstacle piece around (1/2, 1/2)
    @test is_inside(sws, SVector(0.0, 0.0)) === true
    @test is_inside(sws, SVector(0.9, 0.2)) === true
    @test is_inside(sws, SVector(0.7, 0.3)) === true
    @test is_inside(sws, SVector(0.4, -0.4)) === true
    @test is_inside(sws, SVector(0.5, 0.5)) === false        # centre of the obstacle
    @test is_inside(sws, SVector(-0.9, 0.1)) === false       # outside the wedge
    @test is_inside(sws, SVector(0.2, 0.9)) === false
    @test is_inside(sws, SVector(1.2, 0.1)) === false
    # corners of the wedge and of the obstacle piece, then the corners of the physical loops: 4 right angles, 3 pi / 2 at each of the 8 obstacle corners
    @test corner_angles(sws) ≈ [pi / 2, pi / 4, pi / 4, 7pi / 4, 3pi / 2, 7pi / 4, 7pi / 4, 7pi / 4, 3pi / 2] atol = 1e-12
    @test corner_angles(sws; fundamental = false) ≈ [fill(pi / 2, 4); fill(3pi / 2, 8)] atol = 1e-12
    # full boundary: the outer loop, then one loop per obstacle
    @test length(full_boundary(sws)) == 12
    fbs = full_boundary_components(sws)
    @test fbs.is_hole == [false, true, true]
    @test fbs.group == [0, 1, 1]
    @test [sws_loop_length(loop) for loop in fbs.curves] ≈ [8.0, 4 * 0.25, 4 * 0.25] rtol = 1e-12

    # centered obstacle: corners of the reduced domain, then the full physical boundary: two loops of 8 blocks, lengths 8a and 4 size
    @test corner_angles(sym) ≈ [pi / 2, pi / 4, pi / 4, 7pi / 4, 3pi / 2, 7pi / 4] atol = 1e-12
    @test corner_angles(sym; fundamental = false) ≈ [fill(pi / 2, 4); fill(3pi / 2, 4)] atol = 1e-12
    fbc = full_boundary_components(sym)
    @test fbc.is_hole == [false, true]
    @test [length(b) for b in fbc.blocks] == [8, 8]
    @test [sws_loop_length(loop) for loop in fbc.curves] ≈ [8.0, 4 * 0.4] rtol = 1e-12
    @test length(full_boundary(sym)) == 16
    # holes plus a non-empty registry: get_boundary_curves is ambiguous and throws
    @test_throws ArgumentError get_boundary_curves(sym)
    @test_throws ArgumentError get_boundary_curves(sws)
    @test_throws ArgumentError get_boundary_curves(SquareWithinSquareBilliard(1.0; positions=[0.1], sizes=[0.4]))
end

@testset "SquareWithinSquareBilliard argument guards" begin
    # a > 0
    @test_throws ArgumentError SquareWithinSquareBilliard(0.0)
    @test_throws ArgumentError SquareWithinSquareBilliard(-1.0)
    # positions and sizes have the same length
    @test_throws ArgumentError SquareWithinSquareBilliard(1.0; positions=[0.0], sizes=[0.2, 0.3])
    # sizes are positive
    @test_throws ArgumentError SquareWithinSquareBilliard(1.0; positions=[0.0], sizes=[0.0])
    @test_throws ArgumentError SquareWithinSquareBilliard(1.0; positions=[0.0], sizes=[-0.2])
    # holes lie strictly inside the outer square, on either side
    @test_throws ArgumentError SquareWithinSquareBilliard(1.0; positions=[0.9], sizes=[0.3])
    @test_throws ArgumentError SquareWithinSquareBilliard(1.0; positions=[-0.9], sizes=[0.3])
    @test_throws ArgumentError SquareWithinSquareBilliard(1.0; positions=[0.9], sizes=[0.2])
    # holes may neither overlap nor touch
    @test_throws ArgumentError SquareWithinSquareBilliard(1.0; positions=[-0.5, -0.4], sizes=[0.4, 0.4])
    @test_throws ArgumentError SquareWithinSquareBilliard(1.0; positions=[-0.5, -0.3], sizes=[0.2, 0.2])
end

