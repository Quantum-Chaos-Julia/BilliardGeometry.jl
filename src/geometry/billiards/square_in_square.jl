"""
    SquareWithinSquareBilliard{T} <: AbsBilliard

Square `[-a,a] × [-a,a]` containing axis-aligned square obstacles centered on
the diagonal `y = x`.

## Description
The domain is multiply connected with genus equal to the number of obstacles.
Every obstacle is centered on the diagonal, so the billiard always has the
[`DiagonalReflection`](@ref) symmetry and the outer region is the triangle
`(-a,-a)`, `(a,-a)`, `(a,a)` (`domain_id = 1`, two physical sides and a
[`SymmetryWall`](@ref) on the diagonal). Obstacle `i`, counting from the lower
left, is a [`SymmetricHole`](@ref) whose piece is its half below the diagonal,
a [`Polygon`](@ref) with `domain_id = i + 1`.

When the obstacles are also mirror symmetric about the origin (`positions` and
`sizes` invariant under `d → -d`), the symmetry group is the one generated by
the reflections about both diagonals, `DiagonalReflection`, `XYAxisReflection`,
`AntiDiagonalReflection`. The outer region is then the wedge `(0,0)`, `(a,-a)`,
`(a,a)`; an obstacle with `d > 0` stands for itself and its mirror image at `-d`,
and an obstacle centered at the origin is the quarter of its square in the wedge.

A single obstacle centered at the origin (`positions = [0]`) has the full `D₄`
symmetry of [`D4_symmetry`](@ref): the outer region is the fundamental triangle
`0 ≤ y ≤ x ≤ a` (`domain_id = 1`) and the obstacle is a
[`SymmetricHole`](@ref) whose piece is the triangle `(0,0)`, `(h,0)`, `(h,h)`
with `h` half its side (`domain_id = 2`).

## Attributes
* `fundamental_domain::MultiplyConnectedDomain{T}`: Fundamental outer region with the square holes.
* `symmetries::SymmetryRegistry`: [`D4_symmetry`](@ref) for one concentric obstacle, the two-diagonal group for mirror symmetric obstacles, `DiagonalReflection` otherwise.
"""
struct SquareWithinSquareBilliard{T} <: AbsBilliard where T<:Real
    fundamental_domain::MultiplyConnectedDomain{T}
    symmetries::SymmetryRegistry
end

"""
    SquareWithinSquareBilliard(a = 1; positions = [-a/2, a/2], sizes = fill(a/4, length(positions))) → billiard::SquareWithinSquareBilliard

Construct a [`SquareWithinSquareBilliard`](@ref).

## Arguments
* `a`: Half side length of the outer square, must be positive.

## Keyword arguments
* `positions` : Coordinate `d` of the center `(d, d)` of each obstacle on the diagonal.
* `sizes` : Side length of each obstacle, positive and of the same length as `positions`.

## Throws
`ArgumentError` if the lengths differ, a size is not positive, an obstacle does not lie strictly inside the outer square, or two obstacles overlap or touch.
"""
function SquareWithinSquareBilliard(a::T=one(T); positions::AbstractVector{<:Real}=T[-a/2,a/2], sizes::AbstractVector{<:Real}=fill(a/4,length(positions))) where {T<:Real}
    a > zero(T) || throw(ArgumentError("a must be positive; received $a"))
    length(positions) == length(sizes) || throw(ArgumentError("positions and sizes must have the same length"))
    pos = T.(positions); sz = T.(sizes); n = length(pos)
    all(>(zero(T)), sz) || throw(ArgumentError("All square side lengths must be positive"))
    p = sortperm(pos); pos = pos[p]; sz = sz[p]
    @inbounds for i in 1:n
        h = sz[i]/2
        -a < pos[i]-h && pos[i]+h < a || throw(ArgumentError("Square hole $i must lie strictly inside the outer square; received position=$(pos[i]), size=$(sz[i])"))
    end
    @inbounds for i in 1:n-1
        pos[i]+sz[i]/2 < pos[i+1]-sz[i+1]/2 || throw(ArgumentError("Square holes $i and $(i+1) overlap or touch"))
    end
    bc = SpecularReflection()
    o = SVector{2,T}(zero(T),zero(T)); q1 = SVector{2,T}(a,-a); q2 = SVector{2,T}(a,a)
    mirrored = n > 1 && all(i -> isapprox(pos[i], -pos[n+1-i]) && isapprox(sz[i], sz[n+1-i]), 1:n)
    if n == 1 && iszero(pos[1])
        q1 = SVector{2,T}(a,zero(T))
        outer_domain = Polygon([q1,q2,o], 1; bcs=AbsBoundaryCondition[bc, SymmetryWall(1,2), SymmetryWall(7,8)])
        h = sz[1]/2
        piece = Polygon([o,SVector{2,T}(h,zero(T)),SVector{2,T}(h,h)], 2; bcs=AbsBoundaryCondition[SymmetryWall(7,8), bc, SymmetryWall(1,2)])
        symmetries = D4_symmetry()
        holes = AbsDomainHole[SymmetricHole(piece, D4_symmetry(), o)]
    elseif mirrored
        symmetries = register_symmetries(DiagonalReflection(), XYAxisReflection(), AntiDiagonalReflection())
        outer_domain = Polygon([o,q1,q2], 1; bcs=AbsBoundaryCondition[SymmetryWall(3,2), bc, SymmetryWall(1,2)])
        holes = AbsDomainHole[]
        for i in 1:n
            pos[i] < zero(T) && continue
            h = sz[i]/2
            piece = iszero(pos[i]) ?
                Polygon([o,SVector{2,T}(h,-h),SVector{2,T}(h,h)], i+1; bcs=AbsBoundaryCondition[SymmetryWall(3,2), bc, SymmetryWall(1,2)]) :
                _diagonal_hole_piece(pos[i], h, i+1, bc)
            push!(holes, SymmetricHole(piece, register_symmetries(DiagonalReflection(), XYAxisReflection(), AntiDiagonalReflection()), o))
        end
    else
        symmetries = register_symmetries(DiagonalReflection())
        q0 = SVector{2,T}(-a,-a)
        outer_domain = Polygon([q0,q1,q2], 1; bcs=AbsBoundaryCondition[bc, bc, SymmetryWall(1,2)])
        holes = AbsDomainHole[SymmetricHole(_diagonal_hole_piece(pos[i], sz[i]/2, i+1, bc), register_symmetries(DiagonalReflection()), o) for i in 1:n]
    end
    fundamental_domain = MultiplyConnectedDomain(outer_domain, holes, 1)
    validate_holes(fundamental_domain, symmetries)
    billiard = SquareWithinSquareBilliard{T}(fundamental_domain, symmetries)
    
    return billiard
end

# Half below the diagonal `y = x` of the square of half side `h` centered at `(c,c)`.
function _diagonal_hole_piece(c::T, h::T, domain_id::Integer, bc::AbsBoundaryCondition) where {T<:Real}
    return Polygon([SVector{2,T}(c-h,c-h), SVector{2,T}(c+h,c-h), SVector{2,T}(c+h,c+h)], domain_id; bcs=AbsBoundaryCondition[bc, bc, SymmetryWall(1,2)])
end
