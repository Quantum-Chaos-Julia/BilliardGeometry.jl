"""
    C6C3HoleBilliard{T} <: AbsBilliard

Billiard with a sixfold symmetric outer boundary and a threefold symmetric
central hole.

## Description
The outer boundary is `r(φ) = R [1 + a cos 6φ]` (symmetry `C₆`), the hole boundary
is `r(φ) = R_hole [1 + b cos 3φ]` (symmetry `C₃`). The symmetry group of the
billiard is the intersection `C₆ ∩ C₃ = C₃`, a proper subgroup of the symmetry
group of the outer boundary. The fundamental domain is the sector
`0 ≤ φ ≤ 2π/3` of the outer region (a boundary arc and two
[`SymmetryWall`](@ref) radii, `domain_id = 1`) and the hole is a
[`SymmetricHole`](@ref) whose piece is the sector `0 ≤ φ ≤ 2π/3` of the hole
(`domain_id = 2`), with the group generated by [`Cn_symmetry`](@ref)`(3)`.

## Attributes
* `fundamental_domain::MultiplyConnectedDomain{T}`: Outer sector with the hole piece.
* `symmetries::SymmetryRegistry`: Rotations by `2π/3` and `4π/3`.
"""
struct C6C3HoleBilliard{T} <: AbsBilliard where T<:Real
    fundamental_domain::MultiplyConnectedDomain{T}
    symmetries::SymmetryRegistry
end

"""
    C6C3HoleBilliard(a, b; R = 1, R_hole = R/3) → billiard::C6C3HoleBilliard

Construct a [`C6C3HoleBilliard`](@ref).

## Arguments
* `a`: Relative amplitude of the `cos 6φ` deformation of the outer boundary, `|a| < 1`.
* `b`: Relative amplitude of the `cos 3φ` deformation of the hole, `|b| < 1`.

## Keyword arguments
* `R = 1` : Mean radius of the outer boundary.
* `R_hole = R/3` : Mean radius of the hole.

## Throws
`ArgumentError` for non-positive radii, `|a| ≥ 1`, `|b| ≥ 1`, or a hole that does not lie inside the outer boundary.
"""
function C6C3HoleBilliard(a::T, b::T; R=one(T), R_hole=T(R)/3) where T<:Real
    R = T(R); R_hole = T(R_hole)
    R > zero(T) || throw(ArgumentError("R must be positive; received R=$R"))
    R_hole > zero(T) || throw(ArgumentError("R_hole must be positive; received R_hole=$R_hole"))
    abs(a) < one(T) || throw(ArgumentError("|a| must be smaller than 1; received a=$a"))
    abs(b) < one(T) || throw(ArgumentError("|b| must be smaller than 1; received b=$b"))
    R_hole*(one(T)+abs(b)) < R*(one(T)-abs(a)) || throw(ArgumentError("the hole must lie inside the outer boundary; received R=$R, a=$a, R_hole=$R_hole, b=$b"))
    c = SVector{2,T}(zero(T),zero(T))
    bc = SpecularReflection()
    sector = T(2*pi/3)
    outer_coef = SVector{12,T}(ntuple(i -> i==12 ? a*R : zero(T), 12))
    hole_coef = SVector{6,T}(ntuple(i -> i==6 ? b*R_hole : zero(T), 6))

    outer_arc = FourierCoeffPolarSegment(outer_coef; R=R, arc_angle=sector, shift_angle=zero(T), center=c, bc=bc, domain_id=1, segment_id=1)
    p0 = curve(outer_arc, zero(T))
    p1 = curve(outer_arc, one(T))
    outer_wall1 = LineSegment(p1, c; bc=SymmetryWall(1,2), domain_id=1, segment_id=2)
    outer_wall0 = LineSegment(c, p0; bc=SymmetryWall(2,2), domain_id=1, segment_id=3)
    outer_domain = SimpleDomain{T}(AbsCurve[outer_arc, outer_wall1, outer_wall0], SVector{2,T}[p0, p1, c], 1)

    hole_arc = FourierCoeffPolarSegment(hole_coef; R=R_hole, arc_angle=sector, shift_angle=zero(T), center=c, bc=bc, domain_id=2, segment_id=1)
    h0 = curve(hole_arc, zero(T))
    h1 = curve(hole_arc, one(T))
    hole_wall1 = LineSegment(h1, c; bc=SymmetryWall(1,2), domain_id=2, segment_id=2)
    hole_wall0 = LineSegment(c, h0; bc=SymmetryWall(2,2), domain_id=2, segment_id=3)
    piece = SimpleDomain{T}(AbsCurve[hole_arc, hole_wall1, hole_wall0], SVector{2,T}[h0, h1, c], 2)

    symmetries = Cn_symmetry(3; T=T)
    fundamental_domain = MultiplyConnectedDomain(outer_domain, [SymmetricHole(piece, Cn_symmetry(3; T=T), c)], 1)
    validate_holes(fundamental_domain, symmetries)
    billiard = C6C3HoleBilliard{T}(fundamental_domain, symmetries)
    _log_symmetry_group("C6C3HoleBilliard", billiard)
    return billiard
end
